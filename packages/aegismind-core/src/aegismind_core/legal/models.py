from __future__ import annotations

from typing import Any, Literal
from pydantic import BaseModel, Field


class LegalCaseInput(BaseModel):
    """Input payload representing a case file or legal brief for analysis."""
    case_title: str = Field(default="Untitled Case Matter", description="Name/title of the matter")
    case_text: str = Field(..., description="Full text or extracted transcript of the case file")
    case_type: Literal[
        "Criminal", "Civil", "Commercial", "Constitutional", "Corporate/IBC", "Family/Matrimonial", "Consumer", "Other"
    ] = Field(default="Criminal", description="Branch of Indian law")
    court_forum: str = Field(default="High Court / Trial Court", description="Target judicial forum or tribunal")
    client_posture: Literal[
        "Petitioner/Complainant", "Defendant/Accused", "Appellant", "Respondent", "Neutral Review"
    ] = Field(default="Neutral Review", description="Client or advocate perspective")
    specific_questions: list[str] = Field(
        default_factory=list, description="Specific questions or problem points requested by the advocate"
    )


class ExtractedFacts(BaseModel):
    """Structured breakdown of case facts under Indian legal standards."""
    case_title: str = ""
    court_forum: str = ""
    parties: dict[str, str] = Field(default_factory=dict, description="Petitioner/Complainant vs Respondent/Accused")
    key_statutes: list[str] = Field(
        default_factory=list, description="Acts and sections involved (e.g., Sec 138 NI Act, Sec 420 IPC, Sec 9 CPC)"
    )
    chronological_events: list[dict[str, str]] = Field(
        default_factory=list, description="Timeline of dated occurrences"
    )
    undisputed_facts: list[str] = Field(default_factory=list, description="Admitted facts not under dispute")
    disputed_contentions: list[str] = Field(default_factory=list, description="Key points of controversy")
    core_legal_issues: list[str] = Field(default_factory=list, description="Framed legal questions for adjudication")


class WeaknessItem(BaseModel):
    """A vulnerability, legal loophole, or evidentiary defect identified in the case."""
    id: str = Field(default="", description="Unique identifier")
    severity: Literal["CRITICAL", "HIGH", "MODERATE", "LOW"] = "HIGH"
    category: Literal[
        "EVIDENTIARY_DEFECT",
        "PROCEDURAL_IRREGULARITY",
        "STATUTORY_INGREDIENTS_MISSING",
        "LIMITATION_AND_LACHES",
        "JURISDICTIONAL_BAR",
        "FACTUAL_CONTRADICTION",
        "STANDARD_OF_PROOF_DEFICIT"
    ] = "EVIDENTIARY_DEFECT"
    title: str = Field(..., description="Short descriptive title of the weakness")
    description: str = Field(..., description="Detailed explanation of the flaw")
    statutory_basis: str = Field(
        default="", description="Relevant Indian statutory section (e.g. S.65B Evidence Act, S.468 CrPC, Order 7 R.11 CPC)"
    )
    impact_on_case: str = Field(..., description="How this damages the position before the judge")
    opposing_counsel_angle: str = Field(..., description="How opposing advocate will exploit this point")


class StrategyItem(BaseModel):
    """Tactical legal strategy and actionable approach for the advocate."""
    id: str = Field(default="", description="Unique identifier")
    phase: Literal[
        "IMMEDIATE_PRELIMINARY",
        "INTERIM_APPLICATIONS",
        "EVIDENCE_AND_DISCOVERY",
        "CROSS_EXAMINATION_ANGLES",
        "FINAL_ARGUMENTS_OR_SETTLEMENT"
    ] = "IMMEDIATE_PRELIMINARY"
    remedy_title: str = Field(..., description="Name of the strategic move (e.g. Application u/s 482 CrPC for Quashing)")
    procedural_mechanism: str = Field(..., description="Specific legal provision or petition type")
    strategic_rationale: str = Field(..., description="Why this approach gives maximum leverage")
    actionable_steps: list[str] = Field(default_factory=list, description="Immediate steps the advocate must take")
    key_cross_examination_questions: list[str] = Field(
        default_factory=list, description="Targeted cross-examination questions to dismantle the opponent"
    )


class PrecedentItem(BaseModel):
    """Indian case law precedent supporting or distinguishing an argument."""
    case_name: str
    citation: str = Field(default="", description="e.g. (2022) 3 SCR 276 or AIR 2024 SC 112")
    court: str = Field(default="Supreme Court of India", description="Supreme Court or relevant High Court")
    applicable_ratio: str = Field(..., description="Legal principle or holding established in the ruling")
    relevance_summary: str = Field(..., description="How this applies to the current matter")
    stance: Literal["SUPPORTING", "DISTINGUISHING_ADVERSE_AUTHORITY"] = "SUPPORTING"


class LegalAuditReport(BaseModel):
    """Complete, integrated legal analysis report generated by the Multi-Agent Swarm."""
    case_id: str = ""
    case_title: str = ""
    case_type: str = "Criminal"
    overall_strength_score: int = Field(default=50, ge=0, le=100, description="0 (Frivolous/Defective) to 100 (Ironclad)")
    risk_level: Literal["CRITICAL_RISK", "HIGH_RISK", "MODERATE_RISK", "STRONG_POSITION"] = "MODERATE_RISK"
    executive_summary: str = Field(..., description="High-level assessment for the lead advocate")
    facts: ExtractedFacts = Field(default_factory=ExtractedFacts)
    weaknesses: list[WeaknessItem] = Field(default_factory=list)
    strategic_approach: list[StrategyItem] = Field(default_factory=list)
    precedents: list[PrecedentItem] = Field(default_factory=list)
    full_legal_opinion: str = Field(..., description="Comprehensive legal opinion & strategy memorandum")
    deliberation_log: list[dict[str, Any]] = Field(
        default_factory=list, description="Chronological log of multi-agent deliberation events"
    )
